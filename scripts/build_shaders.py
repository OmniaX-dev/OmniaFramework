"""
Compiles the built-in shaders (other/shaders/*.frag.hlsl) with SDL_shadercross into
SPIR-V (Vulkan), MSL (Metal) and DXIL (D3D12), and embeds the results in
src/ogfx/resources/EmbeddedShaders.hpp/.cpp. The generated files are committed,
so normal builds don't need any of this.

Usually run through "./build shaders", which sets up the tools in tools/ first
(scripts/setup-shader-tools.sh) and passes their paths from tools/shader-tools.env.

Usage:
    python3 scripts/build_shaders.py [--shadercross PATH] [--dxc-lib-dir DIR] [--no-dxil]

  --shadercross   the shadercross CLI (default: $SHADERCROSS or "shadercross" from PATH)
  --dxc-lib-dir   directory with libdxcompiler + libdxil to use for DXIL (default:
                  $DXC_LIB_DIR; on Windows the directory with dxcompiler.dll/dxil.dll). DXIL must be signed by the validator
                  (libdxil) to load on D3D12; Microsoft's release builds of DXC ship it.
  --no-dxil       skip DXIL. Without DXIL blobs the framework doesn't enable DXIL on the
                  GPU device, so on Windows SDL picks its Vulkan backend instead of D3D12.

Also available as the CMake target "ogfx_shaders" (defaults to the tools/ paths).
"""

import argparse
import json
import os
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHADER_DIR = ROOT / "other/shaders"
OUT_HPP = ROOT / "src/ogfx/resources/EmbeddedShaders.hpp"
OUT_CPP = ROOT / "src/ogfx/resources/EmbeddedShaders.cpp"
FORMATS = [("spv", "SPIRV"), ("msl", "MSL"), ("dxil", "DXIL")]

