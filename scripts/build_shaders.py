def run_shadercross(shadercross, env, src, dest_format, out_path=None):
	cmd = [shadercross, str(src), "-s", "HLSL", "-d", dest_format, "-t", "fragment"]
	if out_path is not None:
		cmd += ["-o", str(out_path)]
	result = subprocess.run(cmd, env=env, capture_output=True, text=True)
	if result.returncode != 0 or (out_path is not None and (not out_path.exists() or out_path.stat().st_size == 0)):
		raise RuntimeError(f"{' '.join(cmd)}\n{result.stdout}{result.stderr}")
	return result.stdout


def c_array(name, data):
	lines = []
	for i in range(0, len(data), 24):
		lines.append("\t\t" + ", ".join(str(b) for b in data[i:i + 24]) + ",")
	return f"\tconst u32 {name}_size = {len(data)};\n\tconst ostd::UByte {name}_data[{len(data)}] = {{\n" + "\n".join(lines) + "\n\t};\n"


def main():
	parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
	parser.add_argument("--shadercross", default=os.environ.get("SHADERCROSS", "shadercross"))
	parser.add_argument("--dxc-lib-dir", default=os.environ.get("DXC_LIB_DIR"))
	parser.add_argument("--no-dxil", action="store_true")
	args = parser.parse_args()

	shadercross = shutil.which(args.shadercross)
	if shadercross is None:
		print(f"error: shadercross not found: {args.shadercross}\n"
			  "./build shaders (without SHADERCROSS) sets up the shader tools in tools/ when they're missing.", file=sys.stderr)
		return 1
	args.shadercross = shadercross

	env = dict(os.environ)
	if args.dxc_lib_dir:
		# Where the loader looks for libdxcompiler/libdxil (DLLs are searched for on PATH).
		var = "PATH" if os.name == "nt" else "LD_LIBRARY_PATH"
		env[var] = args.dxc_lib_dir + os.pathsep + env.get(var, "")

	sources = sorted(SHADER_DIR.glob("*.frag.hlsl"))
	if not sources:
		print("no shaders found in", SHADER_DIR)
		return 1

	tmp = SHADER_DIR / ".build"
	tmp.mkdir(exist_ok=True)
	formats = [f for f in FORMATS if not (args.no_dxil and f[0] == "dxil")]
	shaders = []
	for src in sources:
		base = src.name[:-len(".hlsl")].replace(".", "_")  # blur.frag.hlsl -> blur_frag
		layout_path = tmp / f"{base}.json"
		run_shadercross(args.shadercross, env, src, "JSON", layout_path)
		layout = json.loads(layout_path.read_text())
		blobs = {}
		for ext, fmt in formats:
			out = tmp / f"{base}.{ext}"
			if out.exists():
				out.unlink()
			try:
				run_shadercross(args.shadercross, env, src, fmt, out)
				blobs[ext] = out.read_bytes()
			except RuntimeError as err:
				print(f"warning: {src.name}: {fmt} compilation failed, the format is left out:\n{err}", file=sys.stderr)
		shaders.append((base, layout, blobs))
		print(f"{src.name}: " + ", ".join(f"{ext} {len(data)} bytes" for ext, data in blobs.items()))

	# A format is only advertised when every shader has it.
	available = [ext for ext, _ in formats if all(ext in blobs for _, _, blobs in shaders)]

	hpp = [LICENSE, "#pragma once\n", "#include <ostd/data/Types.hpp>\n", "namespace ogfx", "{", "\tnamespace embedded_shaders", "\t{"]
	for ext, _ in FORMATS:
		hpp.append(f"\t\tinline constexpr bool HasFormat_{ext.upper()} {{ {'true' if ext in available else 'false'} }};")
	hpp.append("")
	for base, layout, blobs in shaders:
		hpp.append(f"\t\t// {base.replace('_', '.')}.hlsl")
		hpp.append(f"\t\tinline constexpr u32 {base}_num_samplers {{ {layout['samplers']} }};")
		hpp.append(f"\t\tinline constexpr u32 {base}_num_uniform_buffers {{ {layout['uniform_buffers']} }};")
		hpp.append(f"\t\tinline constexpr u32 {base}_num_storage_textures {{ {layout['storage_textures']} }};")
		hpp.append(f"\t\tinline constexpr u32 {base}_num_storage_buffers {{ {layout['storage_buffers']} }};")
		for ext, _ in FORMATS:
			if ext in available:
				hpp.append(f"\t\textern const u32 {base}_{ext}_size;")
				hpp.append(f"\t\textern const ostd::UByte {base}_{ext}_data[];")
		hpp.append("")
	hpp += ["\t}", "}", ""]

	cpp = [LICENSE, '#include "EmbeddedShaders.hpp"\n', "namespace ogfx::embedded_shaders", "{"]
	for base, layout, blobs in shaders:
		for ext, _ in FORMATS:
			if ext in available:
				cpp.append(c_array(f"{base}_{ext}", blobs[ext]))
	cpp += ["}", ""]

	OUT_HPP.write_text("\n".join(hpp))
	OUT_CPP.write_text("\n".join(cpp))
	for f in tmp.iterdir():
		f.unlink()
	tmp.rmdir()
	print(f"formats embedded: {', '.join(available)}")
	print(f"wrote {OUT_HPP.relative_to(ROOT)} and {OUT_CPP.relative_to(ROOT)}")
	return 0


if __name__ == "__main__":
	sys.exit(main())
